# Funksjon for å dekode hex til base64 og deretter til tekst
def hex_to_base64_text(hex_data):
    decoded_text = ""
    for hex_string in hex_data:
        # Konverterer hex til bytes
        byte_data = bytes.fromhex(hex_string)
        # Konverterer bytes til base64
        base64_encoded = base64.b64encode(byte_data).decode('utf-8')
        # Dekoder base64 til tekst
        decoded_text += base64.b64decode(base64_encoded).decode('utf-8', errors='ignore') + "\n"
    return decoded_text

